import React, { useState } from 'react';
import { useAuth } from '../context/AuthContext';
import { ShieldCheck, X, AlertCircle, ArrowRight, RefreshCw, Key } from 'lucide-react';

interface Props {
  onSuccess: () => void;
  onFallbackToRecovery: (identifier: string) => void;
}

export const TwoFactorModal: React.FC<Props> = ({ onSuccess, onFallbackToRecovery }) => {
  const { pending2FAUser, verify2FA, cancel2FA } = useAuth();
  const [code, setCode] = useState('');
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);

  if (!pending2FAUser) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMessage(null);

    if (code.trim().length !== 6) {
      setErrorMessage('Please enter the 6-digit verification code.');
      return;
    }

    setIsSubmitting(true);
    const ok = await verify2FA(code);
    setIsSubmitting(false);

    if (!ok) {
      setErrorMessage('Invalid 2FA code. (Hint: Any 6-digit code such as 123456 will pass the simulation).');
      return;
    }

    onSuccess();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm animate-in fade-in duration-150">
      <div className="w-full max-w-md bg-slate-900 border border-slate-800 rounded-2xl p-6 sm:p-7 shadow-2xl relative">
        <button
          onClick={cancel2FA}
          className="absolute right-4 top-4 text-slate-400 hover:text-white"
        >
          <X className="w-5 h-5" />
        </button>

        <div className="text-center mb-6">
          <div className="w-12 h-12 rounded-xl bg-purple-500/10 text-purple-400 border border-purple-500/20 flex items-center justify-center mx-auto mb-3 shadow-inner">
            <ShieldCheck className="w-6 h-6" />
          </div>
          <h3 className="text-xl font-bold text-white tracking-tight">
            Two-Factor Authentication
          </h3>
          <p className="text-xs text-slate-400 mt-1">
            Enter the 6-digit security code generated by your Authenticator app for{' '}
            <strong className="text-purple-300 font-mono">{pending2FAUser.email}</strong>.
          </p>
        </div>

        {errorMessage && (
          <div className="mb-4 p-3 rounded-xl bg-rose-500/10 border border-rose-500/30 text-rose-300 text-xs flex items-start gap-2">
            <AlertCircle className="w-4 h-4 text-rose-400 shrink-0 mt-0.5" />
            <span>{errorMessage}</span>
          </div>
        )}

        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <input
              type="text"
              maxLength={6}
              inputMode="numeric"
              value={code}
              onChange={e => setCode(e.target.value.replace(/\D/g, ''))}
              placeholder="123456"
              autoFocus
              className="w-full py-3.5 px-4 text-center text-2xl font-mono font-bold tracking-widest rounded-xl bg-slate-950 border border-slate-700 text-white focus:outline-none focus:border-purple-500 focus:ring-1 focus:ring-purple-500 transition-all shadow-inner"
            />
          </div>

          <div className="text-center">
            <button
              type="button"
              onClick={() => {
                const userEmail = pending2FAUser.email;
                cancel2FA();
                onFallbackToRecovery(userEmail);
              }}
              className="text-xs text-purple-400 hover:text-purple-300 flex items-center justify-center gap-1.5 mx-auto font-medium"
            >
              <Key className="w-3.5 h-3.5" />
              <span>Lost your phone? Use Emergency Recovery</span>
            </button>
          </div>

          <button
            type="submit"
            disabled={isSubmitting || code.length !== 6}
            className="w-full py-3 px-4 rounded-xl bg-purple-600 hover:bg-purple-500 disabled:opacity-50 text-white font-semibold text-sm shadow-lg shadow-purple-600/25 transition-all flex items-center justify-center gap-2"
          >
            {isSubmitting ? (
              <>
                <RefreshCw className="w-4 h-4 animate-spin" />
                <span>Verifying...</span>
              </>
            ) : (
              <>
                <span>Authenticate Session</span>
                <ArrowRight className="w-4 h-4" />
              </>
            )}
          </button>
        </form>
      </div>
    </div>
  );
};
